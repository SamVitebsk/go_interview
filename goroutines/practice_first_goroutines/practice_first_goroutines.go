package main

import (
	"fmt"
	"sync"
)

// 1. Как выполняется этот код и почему порядок вывода чисел заранее не определён:
// Родительская горутина последовательно регистрирует задачи через wg.Add и запускает 5 независимых
// горутин. Рантайм Go помещает созданные структуры горутин (G) в локальные очереди
// планировщика (P). Планировщик Go и планировщик ядра ОС распределяют горутины и потоки (M) по ядрам
// CPU недетерминированно: очередность получения процессорного времени и момент выполнения
// случайны, поэтому порядок чисел меняется от запуска к запуску.
//
// 2. Почему time.Sleep нельзя использовать для ожидания завершения горутин:
// Время выполнения горутин непредсказуемо и зависит от загрузки CPU, задержек планирования и пауз GC:
//   - Если таймера не хватит, вызывающая функция завершится раньше времени, что приведет к преждевременному
//     уничтожению горутин процессом и потере данных.
//   - Если таймер взят с запасом, программа впустую простаивает, ухудшая пропускную способность (latency).
//
// Использование sync.WaitGroup обеспечивает детерминированное пробуждение строго по факту завершения всех задач.
//
// 3. Защита замыкания:
// Значение val передается явно параметром в горутину (v int), гарантируя независимую копию числа
// и потокобезопасность независимо от версии Go и настроек go.mod.
func main() {
	values := []int{1, 2, 3, 4, 5}

	var wg sync.WaitGroup
	wg.Add(len(values))

	for _, val := range values {
		go func(v int) {
			defer wg.Done()
			fmt.Println(v)
		}(val)
	}

	wg.Wait()
}
